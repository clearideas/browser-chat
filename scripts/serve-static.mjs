#!/usr/bin/env node
// Serves the repository's files (dev.html, the built dist/, test pages) for local testing and the
// browser tests. Node.js built-ins only.
//
//   node scripts/serve-static.mjs [--port 8000] [--host 127.0.0.1] [--api-url http://127.0.0.1:8787]
//
// `/dev-config.js` tells the pages where the test server is (`window.CHAT_DEV_API_URL`, from
// --api-url or DEV_API_URL), so it can run on another port.
//
// Local use only: no directory listings, only files inside the repository, no caching. A directory
// request is answered with its index.html when there is one (so / is the repository's index page).

import { createReadStream, statSync } from 'node:fs'
import { createServer } from 'node:http'
import { extname, join, normalize, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'

const ROOT = fileURLToPath(new URL('..', import.meta.url))

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.cjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.map': 'application/json; charset=utf-8',
  // Plain text so documentation opens in the browser instead of downloading.
  '.md': 'text/plain; charset=utf-8',
  '.yaml': 'text/plain; charset=utf-8',
  '.yml': 'text/plain; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
}

const { values } = parseArgs({
  options: {
    port: { type: 'string', default: process.env.PORT ?? '8000' },
    host: { type: 'string', default: process.env.HOST ?? '127.0.0.1' },
    'api-url': { type: 'string', default: process.env.DEV_API_URL ?? 'http://127.0.0.1:8787' },
  },
})

const DEV_CONFIG = `// Generated by scripts/serve-static.mjs\nwindow.CHAT_DEV_API_URL = ${JSON.stringify(
  values['api-url'].replace(/\/+$/, ''),
)}\n`

/** The file for a URL path, or null if it is outside the repository or not a file. */
function resolveFile(urlPath) {
  let pathname
  try {
    pathname = decodeURIComponent(urlPath)
  } catch {
    return null
  }
  const file = normalize(join(ROOT, pathname))
  if (file !== ROOT && !file.startsWith(ROOT.endsWith(sep) ? ROOT : ROOT + sep)) return null
  try {
    const stats = statSync(file)
    if (stats.isFile()) return file
    if (stats.isDirectory()) {
      const index = join(file, 'index.html')
      return statSync(index).isFile() ? index : null
    }
    return null
  } catch {
    return null
  }
}

const server = createServer((req, res) => {
  const { pathname } = new URL(req.url ?? '/', 'http://localhost')
  if (pathname === '/dev-config.js' && (req.method === 'GET' || req.method === 'HEAD')) {
    res.writeHead(200, { 'Content-Type': TYPES['.js'], 'Cache-Control': 'no-store' })
    res.end(req.method === 'HEAD' ? undefined : DEV_CONFIG)
    return
  }
  const file = req.method === 'GET' || req.method === 'HEAD' ? resolveFile(pathname) : null
  if (!file) {
    res.writeHead(404, { 'Content-Type': 'text/plain; charset=utf-8' })
    res.end('Not found')
    return
  }
  res.writeHead(200, {
    'Content-Type': TYPES[extname(file)] ?? 'application/octet-stream',
    'Cache-Control': 'no-store',
  })
  if (req.method === 'HEAD') res.end()
  else createReadStream(file).pipe(res)
})

server.on('error', error => {
  console.error(
    error.code === 'EADDRINUSE'
      ? `Port ${values.port} is in use. Serve the pages on another port: --port 8100`
      : error.code === 'EACCES'
        ? `Port ${values.port} cannot be used (on Windows it may be reserved: netsh interface ipv4 show excludedportrange protocol=tcp). Try --port 8100`
        : `Could not listen on ${values.host}:${values.port}: ${error.message}`,
  )
  process.exit(1)
})

server.listen(Number(values.port), values.host, () => {
  const address = server.address()
  console.log(`Static files on http://${values.host}:${address.port}/ (from ${ROOT})`)
})

for (const signal of ['SIGINT', 'SIGTERM']) {
  process.on(signal, () => server.close(() => process.exit(0)))
}
// Started by scripts/dev.mjs (with an IPC channel): exit when it does, even if it was killed,
// since Windows does not end child processes with their parent.
if (process.send) process.on('disconnect', () => process.exit(0))
